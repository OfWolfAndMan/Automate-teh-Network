#!/usr/bin/env python3
"""Generate the README inventory table from per-playbook metadata.

The rule this enforces: a playbook states when it was last executed and against what, or it
states that it was never executed. The table is a projection of those statements, so it
cannot drift the way a hand-maintained table does.

Metadata lives in a YAML block at the top of each playbook, inside comments:

    # ---
    # title: Back up device configurations
    # status: verified
    # verified_on: 2026-11-11
    # verified_env: ansible-core 2.22.0, containerlab, cEOS 4.31.2F
    # note: optional free text
    # ---

Statuses: verified | partial | unverified | retired. Anything else is an error, because a
typo that silently renders as "unknown" is how a status table rots.

Usage:
  python3 tools/gen_index.py --check     report drift, exit 1 if the README is stale
  python3 tools/gen_index.py --write     rewrite the table in place
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARK_START = "<!-- INDEX:START -->"
MARK_END = "<!-- INDEX:END -->"
VALID = {"verified", "partial", "unverified", "retired"}

# The block sits after the YAML document marker, so it is found anywhere in the head of
# the file rather than anchored to byte 0.
META_RE = re.compile(r"(?ms)^#[ \t]*---[ \t]*\n(.*?)^#[ \t]*---[ \t]*\n")


def parse_meta(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    m = META_RE.search(text)
    if not m:
        return {}
    out: dict[str, str] = {}
    for line in m.group(1).splitlines():
        line = line.lstrip("#").strip()
        if not line or ":" not in line:
            continue
        k, v = line.split(":", 1)
        out[k.strip()] = v.strip()
    return out


def collect() -> list[dict[str, str]]:
    rows = []
    for p in sorted((ROOT / "playbooks").rglob("*.yml")):
        meta = parse_meta(p)
        rel = str(p.relative_to(ROOT))
        if not meta:
            rows.append({"playbook": rel, "title": "—", "status": "unverified",
                         "verified_on": "—", "verified_env": "no metadata block", "note": ""})
            continue
        status = meta.get("status", "").lower()
        if status not in VALID:
            print(f"ERROR: {rel}: status {meta.get('status')!r} is not one of {sorted(VALID)}",
                  file=sys.stderr)
            raise SystemExit(2)
        rows.append({
            "playbook": rel,
            "title": meta.get("title", "—"),
            "status": status,
            "verified_on": meta.get("verified_on", "—"),
            "verified_env": meta.get("verified_env", "—"),
            "note": meta.get("note", ""),
        })
    return rows


def render(rows: list[dict[str, str]]) -> str:
    lines = [
        MARK_START,
        "",
        "| Playbook | Purpose | Status | Verified | Environment |",
        "|----------|---------|--------|----------|-------------|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['playbook']}` | {r['title']} | **{r['status']}** | "
            f"{r['verified_on']} | {r['verified_env']} |"
        )
    lines += ["", f"_{len(rows)} playbooks. Generated by `tools/gen_index.py`._", "", MARK_END]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    a = ap.parse_args()

    table = render(collect())
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")

    if MARK_START not in readme or MARK_END not in readme:
        print(f"ERROR: README.md is missing {MARK_START} / {MARK_END}", file=sys.stderr)
        return 2

    new = re.sub(re.escape(MARK_START) + r".*?" + re.escape(MARK_END), table, readme, flags=re.S)
    if a.check:
        if new != readme:
            print("STALE: README index does not match playbook metadata", file=sys.stderr)
            return 1
        print("README index is current")
        return 0

    readme_path.write_text(new, encoding="utf-8")
    print(f"README index written ({len(collect())} playbooks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
